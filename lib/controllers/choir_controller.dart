import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

import '../models/models.dart';
import '../services/choir_service.dart';
import '../utils/logger.dart';

class ChoirController extends ChangeNotifier {
  final ChoirService _choirService = ChoirService();
  static const String _selectedChoirKey = 'selected_choir';

  List<ChoirModel> _choirs = [];
  List<ChoirMemberModel> _choirMembers = [];
  ChoirModel? _selectedChoir;
  bool _isLoading = false;
  String? _errorMessage;
  bool _initialized = false;

  List<ChoirModel> get choirs => _choirs;
  List<ChoirMemberModel> get choirMembers => _choirMembers;
  ChoirModel? get selectedChoir => _selectedChoir;
  bool get isLoading => _isLoading;
  String? get errorMessage => _errorMessage;
  bool get isInitialized => _initialized;

  // Initialize the controller and restore persisted choir selection
  Future<void> initialize() async {
    if (_initialized) return;
    
    try {
      Logger.debug('ChoirController - Initializing and restoring choir selection');
      await _restoreSelectedChoir();
      _initialized = true;
    } catch (e) {
      Logger.error('ChoirController - Error during initialization: $e');
    }
  }

  // Load all choirs
  Future<void> loadChoirs({String? userId, bool adminView = false}) async {
    try {
      _setLoading(true);
      _clearError();
      
      if (adminView) {
        _choirs = await _choirService.getAllChoirs();
      } else if (userId != null) {
        // Load choirs where user is admin or leader
        final adminChoirs = await _choirService.getChoirsByAdmin(userId);
        final leaderChoirs = await _choirService.getChoirsByLeader(userId);
        
        // Combine and remove duplicates
        final allChoirs = [...adminChoirs, ...leaderChoirs];
        final uniqueChoirs = <String, ChoirModel>{};
        for (final choir in allChoirs) {
          uniqueChoirs[choir.id] = choir;
        }
        _choirs = uniqueChoirs.values.toList();
      } else {
        _choirs = await _choirService.getAllChoirs();
      }
      
      _setLoading(false);
    } catch (e) {
      _setError('Failed to load choirs: $e');
      _setLoading(false);
    }
  }

  // Create new choir
  Future<bool> createChoir({
    required String name,
    required String description,
    required String adminId,
    String? leaderId,
    String? imageUrl,
    String? country,
    String? diocese,
    String? parish,
  }) async {
    try {
      _setLoading(true);
      _clearError();

      final choir = ChoirModel(
        id: '', // Will be generated by database
        name: name,
        description: description,
        leaderId: leaderId ?? adminId,
        adminId: adminId,
        createdAt: DateTime.now(),
        imageUrl: imageUrl,
        country: country,
        diocese: diocese,
        parish: parish,
      );

      await _choirService.createChoir(choir);
      
      // Reload choirs to get the updated list
      await loadChoirs(userId: adminId, adminView: true);
      
      _setLoading(false);
      return true;
    } catch (e) {
      _setError('Failed to create choir: $e');
      _setLoading(false);
      return false;
    }
  }

  // Select a choir and load its members
  Future<void> selectChoir(ChoirModel choir) async {
    try {
      _selectedChoir = choir;
      _setLoading(true);
      _clearError();
      
      // Persist the selected choir
      await _persistSelectedChoir(choir);
      Logger.debug('ChoirController - Selected and persisted choir: ${choir.name}');
      
      _choirMembers = await _choirService.getChoirMembers(choir.id);
      
      _setLoading(false);
      notifyListeners();
    } catch (e) {
      _setError('Failed to load choir members: $e');
      _setLoading(false);
    }
  }

  // Update choir information
  Future<bool> updateChoir(ChoirModel choir) async {
    try {
      Logger.debug('ChoirController: Starting updateChoir for ID: ${choir.id}');
      Logger.debug('ChoirController: Choir name to update: "${choir.name}"');
      
      _setLoading(true);
      _clearError();

      final success = await _choirService.updateChoir(choir);
      Logger.debug('ChoirController: Service returned success: $success');
      
      if (success) {
        // Update local data
        final index = _choirs.indexWhere((c) => c.id == choir.id);
        Logger.debug('ChoirController: Found choir at index: $index');
        if (index != -1) {
          Logger.debug('ChoirController: Updating local choir from "${_choirs[index].name}" to "${choir.name}"');
          _choirs[index] = choir;
        }
        if (_selectedChoir?.id == choir.id) {
          Logger.debug('ChoirController: Updating selected choir from "${_selectedChoir?.name}" to "${choir.name}"');
          _selectedChoir = choir;
        }
        notifyListeners(); // Ensure UI updates
      } else {
        Logger.error('ChoirController: Update failed, error: $errorMessage');
      }
      
      _setLoading(false);
      return success;
    } catch (e) {
      _setError('Failed to update choir: $e');
      _setLoading(false);
      return false;
    }
  }

  // Delete choir
  Future<bool> deleteChoir(String choirId) async {
    try {
      _setLoading(true);
      _clearError();

      final success = await _choirService.deleteChoir(choirId);
      
      if (success) {
        _choirs.removeWhere((c) => c.id == choirId);
        if (_selectedChoir?.id == choirId) {
          _selectedChoir = null;
          _choirMembers.clear();
        }
      }
      
      _setLoading(false);
      return success;
    } catch (e) {
      _setError('Failed to delete choir: $e');
      _setLoading(false);
      return false;
    }
  }

  // Search choirs
  Future<void> searchChoirs(String query) async {
    try {
      _setLoading(true);
      _clearError();
      
      _choirs = await _choirService.searchChoirs(query);
      
      _setLoading(false);
      notifyListeners(); // Ensure UI updates with search results
    } catch (e) {
      _setError('Failed to search choirs: $e');
      _setLoading(false);
    }
  }

  // Add member to choir
  Future<bool> addMemberToChoir({
    required String userId,
    required String choirId,
    required String registrationNumber,
  }) async {
    try {
      _setLoading(true);
      _clearError();

      final member = ChoirMemberModel(
        id: '', // Will be generated by database
        userId: userId,
        choirId: choirId,
        registrationNumber: registrationNumber,
        joinDate: DateTime.now(),
      );

      // Add member to choir
      await _choirService.addMemberToChoir(member);
      
      // Reload choir members
      if (_selectedChoir?.id == choirId) {
        _choirMembers = await _choirService.getChoirMembers(choirId);
      }
      
      _setLoading(false);
      return true;
    } catch (e) {
      _setError('Failed to add member to choir: $e');
      _setLoading(false);
      return false;
    }
  }

  // Remove member from choir
  Future<bool> removeMemberFromChoir({
    required String memberId,
    required String choirId,
  }) async {
    try {
      _setLoading(true);
      _clearError();

      final success = await _choirService.removeMemberFromChoir(memberId, choirId);
      
      if (success) {
        // Reload choir members
        if (_selectedChoir?.id == choirId) {
          _choirMembers = await _choirService.getChoirMembers(choirId);
        }
      }
      
      _setLoading(false);
      return success;
    } catch (e) {
      _setError('Failed to remove member from choir: $e');
      _setLoading(false);
      return false;
    }
  }

  // Get choir statistics
  Future<Map<String, dynamic>> getChoirStatistics(String choirId) async {
    try {
      final members = await _choirService.getChoirMembers(choirId);
      
      final activeMembers = members.where((m) => m.status == MemberStatus.active).length;
      final inactiveMembers = members.where((m) => m.status == MemberStatus.inactive).length;
      final suspendedMembers = members.where((m) => m.status == MemberStatus.suspended).length;
      
      final totalOutstandingFees = members.fold<double>(
        0, (sum, member) => sum + member.outstandingFees
      );
      
      final totalPaid = members.fold<double>(
        0, (sum, member) => sum + member.totalPaid
      );

      return {
        'total_members': members.length,
        'active_members': activeMembers,
        'inactive_members': inactiveMembers,
        'suspended_members': suspendedMembers,
        'total_outstanding_fees': totalOutstandingFees,
        'total_paid': totalPaid,
        'average_attendance': members.isNotEmpty 
            ? members.map((m) => m.attendanceRate).reduce((a, b) => a + b) / members.length
            : 0.0,
      };
    } catch (e) {
      Logger.error('Error getting choir statistics: $e');
      return {};
    }
  }

  // Clear selected choir
  void clearSelection() {
    _selectedChoir = null;
    _choirMembers.clear();
    // Clear persisted selection
    _clearPersistedChoir();
    Logger.debug('ChoirController - Cleared choir selection');
    notifyListeners();
  }

  // Private helper methods
  void _setLoading(bool loading) {
    _isLoading = loading;
    notifyListeners();
  }

  void _setError(String error) {
    _errorMessage = error;
    notifyListeners();
  }

  void _clearError() {
    _errorMessage = null;
  }

  void clearError() {
    _clearError();
    notifyListeners();
  }

  // Persist selected choir to SharedPreferences
  Future<void> _persistSelectedChoir(ChoirModel choir) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final choirJson = jsonEncode(choir.toJson());
      await prefs.setString(_selectedChoirKey, choirJson);
    } catch (e) {
      Logger.error('ChoirController - Error persisting choir: $e');
    }
  }

  // Restore selected choir from SharedPreferences
  Future<void> _restoreSelectedChoir() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final choirJson = prefs.getString(_selectedChoirKey);
      
      if (choirJson != null) {
        final choirData = jsonDecode(choirJson) as Map<String, dynamic>;
        _selectedChoir = ChoirModel.fromJson(choirData);
        Logger.debug('ChoirController - Restored choir selection: ${_selectedChoir!.name}');
        
        // Load choir members for the restored choir
        try {
          _choirMembers = await _choirService.getChoirMembers(_selectedChoir!.id);
        } catch (e) {
          Logger.error('ChoirController - Error loading members for restored choir: $e');
        }
        
        notifyListeners();
      } else {
        Logger.debug('ChoirController - No persisted choir selection found');
      }
    } catch (e) {
      Logger.error('ChoirController - Error restoring choir selection: $e');
    }
  }

  // Clear persisted choir selection
  Future<void> _clearPersistedChoir() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.remove(_selectedChoirKey);
    } catch (e) {
      Logger.error('ChoirController - Error clearing persisted choir: $e');
    }
  }
}