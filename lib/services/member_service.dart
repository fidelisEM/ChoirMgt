import 'package:flutter/foundation.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../models/models.dart';
import 'error_service.dart';
import 'validation_service.dart';

class MemberService {
  factory MemberService() => _instance;
  MemberService._internal();
  static final MemberService _instance = MemberService._internal();

  final SupabaseClient _supabase = Supabase.instance.client;
  final ErrorService _errorService = ErrorService();
  final ValidationService _validationService = ValidationService();

  // Check if user is already a member of the choir
  Future<bool> isUserAlreadyMember({
    required String userId,
    required String choirId,
  }) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .select('id')
          .eq('user_id', userId)
          .eq('choir_id', choirId)
          .maybeSingle();
      
      return response != null;
    } catch (e) {
      debugPrint('Error checking if user is already member: $e');
      return false;
    }
  }

  // Check if registration number exists in choir
  Future<bool> isRegistrationNumberTaken({
    required String registrationNumber,
    required String choirId,
  }) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .select('id')
          .eq('registration_number', registrationNumber)
          .eq('choir_id', choirId)
          .maybeSingle();
      
      return response != null;
    } catch (e) {
      debugPrint('Error checking registration number: $e');
      return false;
    }
  }

  // Add member to choir with validation
  Future<ChoirMemberModel?> addMemberToChoir({
    required String userId,
    required String choirId,
    required String registrationNumber,
    MemberRole role = MemberRole.choir,
    MemberLevel level = MemberLevel.choir,
    Map<String, dynamic>? metadata,
  }) async {
    try {
      // Validate inputs
      final validationErrors = <String>[];
      
      if (userId.isEmpty) validationErrors.add('User ID is required');
      if (choirId.isEmpty) validationErrors.add('Choir ID is required');
      
      final regNumberValidation = _validationService.validateRegistrationNumber(registrationNumber);
      if (!regNumberValidation.isValid) {
        validationErrors.add(regNumberValidation.error!);
      }

      if (validationErrors.isNotEmpty) {
        final error = _errorService.createValidationError(
          validationErrors.join('. ')
        );
        _errorService.logError(error);
        throw error;
      }

      // Check if user is already a member
      final alreadyMember = await isUserAlreadyMember(
        userId: userId,
        choirId: choirId,
      );
      if (alreadyMember) {
        final error = _errorService.createValidationError(
          'This user is already a member of this choir'
        );
        _errorService.logError(error);
        throw error;
      }

      // Check if registration number is taken
      final regNumberTaken = await isRegistrationNumberTaken(
        registrationNumber: registrationNumber.trim(),
        choirId: choirId,
      );
      if (regNumberTaken) {
        final error = _errorService.createValidationError(
          'Registration number "$registrationNumber" is already taken'
        );
        _errorService.logError(error);
        throw error;
      }

      final member = ChoirMemberModel(
        id: '', // Will be generated by database
        userId: userId,
        choirId: choirId,
        registrationNumber: _validationService.sanitizeForDatabase(registrationNumber.trim()),
        joinDate: DateTime.now(),
        role: role,
        level: level,
        metadata: metadata ?? {},
      );

      final response = await _supabase
          .from('choir_members')
          .insert(member.toJson())
          .select()
          .single();

      return ChoirMemberModel.fromJson(response);
    } catch (e) {
      if (e is AppError) {
        rethrow; // Re-throw our custom errors
      }
      
      // Handle Supabase/database errors
      final error = _errorService.createDatabaseError(
        'Failed to add member to choir. Please try again.',
        technicalMessage: e.toString(),
      );
      _errorService.logError(error);
      throw error;
    }
  }

  // Get all choir members with user details
  Future<List<Map<String, dynamic>>> getChoirMembersWithUserInfo(String choirId) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .select('''
            *,
            users!choir_members_user_id_fkey (
              id,
              email,
              full_name,
              phone_number,
              profile_image_url
            )
          ''')
          .eq('choir_id', choirId)
          .order('join_date', ascending: false);

      return List<Map<String, dynamic>>.from(response);
    } catch (e) {
      debugPrint('Error fetching choir members with user info: $e');
      return [];
    }
  }

  // Update member status
  Future<ChoirMemberModel?> updateMemberStatus({
    required String memberId,
    required MemberStatus status,
  }) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .update({'status': status.toString().split('.').last})
          .eq('id', memberId)
          .select()
          .single();

      return ChoirMemberModel.fromJson(response);
    } catch (e) {
      debugPrint('Error updating member status: $e');
      return null;
    }
  }

  // Remove member from choir
  Future<bool> removeMemberFromChoir(String memberId) async {
    try {
      await _supabase
          .from('choir_members')
          .delete()
          .eq('id', memberId);

      return true;
    } catch (e) {
      debugPrint('Error removing member from choir: $e');
      return false;
    }
  }

  // Update member details
  Future<ChoirMemberModel?> updateMemberDetails({
    required String memberId,
    String? registrationNumber,
    double? outstandingFees,
    String? qrCode,
    Map<String, dynamic>? metadata,
  }) async {
    try {
      final updates = <String, dynamic>{};
      
      if (registrationNumber != null) {
        updates['registration_number'] = registrationNumber;
      }
      if (outstandingFees != null) {
        updates['outstanding_fees'] = outstandingFees;
      }
      if (qrCode != null) {
        updates['qr_code'] = qrCode;
      }
      if (metadata != null) {
        updates['metadata'] = metadata;
      }

      if (updates.isEmpty) return null;

      final response = await _supabase
          .from('choir_members')
          .update(updates)
          .eq('id', memberId)
          .select()
          .single();

      return ChoirMemberModel.fromJson(response);
    } catch (e) {
      debugPrint('Error updating member details: $e');
      return null;
    }
  }

  // Search available users to add to choir
  Future<List<UserModel>> searchUsersToAdd({
    required String choirId,
    required String query,
  }) async {
    try {
      if (query.trim().isEmpty) {
        return [];
      }

      // Get users who are not already members of this choir
      // Search by both name and email
      final response = await _supabase
          .from('users')
          .select()
          .or('full_name.ilike.%$query%,email.ilike.%$query%')
          .not('id', 'in', '(SELECT user_id FROM choir_members WHERE choir_id = $choirId)')
          .limit(10);

      return response
          .map<UserModel>((json) => UserModel.fromJson(json))
          .where((user) => user.id.isNotEmpty)
          .toList();
    } catch (e) {
      debugPrint('Error searching users: $e');
      return [];
    }
  }

  // Get member statistics for a choir
  Future<Map<String, dynamic>> getMemberStatistics(String choirId) async {
    try {
      final members = await _supabase
          .from('choir_members')
          .select('status, outstanding_fees, total_paid')
          .eq('choir_id', choirId);

      final total = members.length;
      final active = members.where((m) => m['status'] == 'active').length;
      final inactive = members.where((m) => m['status'] == 'inactive').length;
      final suspended = members.where((m) => m['status'] == 'suspended').length;

      final totalOutstanding = members.fold<double>(
        0, (sum, m) => sum + (m['outstanding_fees'] ?? 0.0)
      );
      final totalPaid = members.fold<double>(
        0, (sum, m) => sum + (m['total_paid'] ?? 0.0)
      );

      return {
        'total_members': total,
        'active_members': active,
        'inactive_members': inactive,
        'suspended_members': suspended,
        'total_outstanding': totalOutstanding,
        'total_paid': totalPaid,
      };
    } catch (e) {
      debugPrint('Error getting member statistics: $e');
      return {};
    }
  }

  // Generate unique registration number
  Future<String> generateRegistrationNumber(String choirId) async {
    try {
      final choir = await _supabase
          .from('choirs')
          .select('name')
          .eq('id', choirId)
          .single();

      final choirName = choir['name'] as String;
      final prefix = choirName.length >= 3 
          ? choirName.substring(0, 3).toUpperCase()
          : 'CHR';

      // Get current member count to generate next number
      final memberCount = await _supabase
          .from('choir_members')
          .select('id')
          .eq('choir_id', choirId)
          .count();

      final nextNumber = (memberCount.count + 1).toString().padLeft(3, '0');
      return '$prefix$nextNumber';
    } catch (e) {
      debugPrint('Error generating registration number: $e');
      return 'CHR001';
    }
  }

  // Update member role
  Future<bool> updateMemberRole({
    required String memberId,
    required String newRole,
  }) async {
    try {
      await _supabase
          .from('choir_members')
          .update({'role': newRole})
          .eq('id', memberId);

      return true;
    } catch (e) {
      debugPrint('Error updating member role: $e');
      return false;
    }
  }

  // Bulk add members (for importing)
  Future<List<ChoirMemberModel>> bulkAddMembers(
    List<Map<String, dynamic>> membersData,
  ) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .insert(membersData)
          .select();

      return response.map<ChoirMemberModel>((json) => 
          ChoirMemberModel.fromJson(json)).toList();
    } catch (e) {
      debugPrint('Error bulk adding members: $e');
      return [];
    }
  }

  // Update member level
  Future<bool> updateMemberLevel({
    required String memberId,
    required String newLevel,
  }) async {
    try {
      final response = await _supabase
          .from('choir_members')
          .update({'level': newLevel})
          .eq('id', memberId)
          .select();
      
      return response.isNotEmpty;
    } catch (e) {
      debugPrint('Error updating member level: $e');
      return false;
    }
  }
}