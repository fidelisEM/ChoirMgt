import '../models/models.dart';

class AttendanceTimeService {
  factory AttendanceTimeService() => _instance;
  AttendanceTimeService._internal();
  static final AttendanceTimeService _instance = AttendanceTimeService._internal();

  // Time-based attendance rules
  static const int defaultGraceMinutes = 15;
  static const int lateGraceMinutes = 30; // After this, marked as absent
  
  /// Determines attendance status based on check-in time and session timing
  AttendanceStatus determineAttendanceStatus({
    required DateTime checkInTime,
    required DateTime sessionStartTime,
    required int graceMinutes,
    bool autoMarkAbsent = true,
  }) {
    final timeDifference = checkInTime.difference(sessionStartTime);
    
    // If checked in before or on time
    if (timeDifference.inMinutes <= 0) {
      return AttendanceStatus.present;
    }
    
    // If checked in within grace period
    if (timeDifference.inMinutes <= graceMinutes) {
      return AttendanceStatus.present;
    }
    
    // If checked in after grace period but within late threshold
    if (timeDifference.inMinutes <= lateGraceMinutes) {
      return AttendanceStatus.late;
    }
    
    // If checked in very late and auto-absent is enabled
    if (autoMarkAbsent) {
      return AttendanceStatus.absent;
    }
    
    // Default to late if auto-absent is disabled
    return AttendanceStatus.late;
  }

  /// Checks if a session should auto-close (mark remaining members as absent)
  bool shouldAutoCloseSession({
    required DateTime sessionStartTime,
    required int graceMinutes,
    DateTime? currentTime,
  }) {
    final now = currentTime ?? DateTime.now();
    final autoCloseTime = sessionStartTime.add(Duration(minutes: graceMinutes + lateGraceMinutes));
    
    return now.isAfter(autoCloseTime);
  }

  /// Gets the time remaining before auto-close
  Duration getTimeUntilAutoClose({
    required DateTime sessionStartTime,
    required int graceMinutes,
    DateTime? currentTime,
  }) {
    final now = currentTime ?? DateTime.now();
    final autoCloseTime = sessionStartTime.add(Duration(minutes: graceMinutes + lateGraceMinutes));
    
    return autoCloseTime.difference(now);
  }

  /// Processes bulk attendance for members not yet marked
  List<AttendanceRecord> processBulkAbsent({
    required List<String> unmarkedMemberIds,
    required String sessionId,
    required String choirId,
    required DateTime eventDate,
    required String recordedBy,
  }) {
    final records = <AttendanceRecord>[];
    final now = DateTime.now();
    
    for (final memberId in unmarkedMemberIds) {
      final record = AttendanceRecord(
        id: '', // Will be generated by database
        sessionId: sessionId,
        memberId: memberId,
        userId: memberId, // Assuming member ID is user ID for now
        choirId: choirId,
        eventDate: eventDate,
        status: AttendanceStatus.absent,
        recordedBy: recordedBy,
        recordedAt: now,
        checkInTime: null, // No check-in time for absent
        notes: 'Auto-marked absent - did not check in',
      );
      records.add(record);
    }
    
    return records;
  }

  /// Validates if a check-in time is reasonable
  bool isValidCheckInTime({
    required DateTime checkInTime,
    required DateTime sessionStartTime,
    int maxEarlyMinutes = 60,
    int maxLateMinutes = 120,
  }) {
    final timeDifference = checkInTime.difference(sessionStartTime);
    
    // Too early
    if (timeDifference.inMinutes < -maxEarlyMinutes) {
      return false;
    }
    
    // Too late
    if (timeDifference.inMinutes > maxLateMinutes) {
      return false;
    }
    
    return true;
  }

  /// Gets attendance session timing information
  Map<String, dynamic> getSessionTimingInfo({
    required DateTime sessionStartTime,
    required int graceMinutes,
    DateTime? currentTime,
  }) {
    final now = currentTime ?? DateTime.now();
    final graceEndTime = sessionStartTime.add(Duration(minutes: graceMinutes));
    final lateEndTime = sessionStartTime.add(const Duration(minutes: lateGraceMinutes));
    final autoCloseTime = sessionStartTime.add(Duration(minutes: graceMinutes + lateGraceMinutes));
    
    final sessionStatus = _getSessionStatus(
      sessionStartTime: sessionStartTime,
      graceEndTime: graceEndTime,
      autoCloseTime: autoCloseTime,
      currentTime: now,
    );
    
    return {
      'sessionStartTime': sessionStartTime,
      'graceEndTime': graceEndTime,
      'lateEndTime': lateEndTime,
      'autoCloseTime': autoCloseTime,
      'currentTime': now,
      'status': sessionStatus,
      'timeUntilStart': sessionStartTime.difference(now),
      'timeUntilGraceEnd': graceEndTime.difference(now),
      'timeUntilAutoClose': autoCloseTime.difference(now),
      'isActive': sessionStatus == 'active' || sessionStatus == 'grace' || sessionStatus == 'late',
      'canCheckIn': sessionStatus != 'closed' && sessionStatus != 'pending',
    };
  }

  String _getSessionStatus({
    required DateTime sessionStartTime,
    required DateTime graceEndTime,
    required DateTime autoCloseTime,
    required DateTime currentTime,
  }) {
    if (currentTime.isBefore(sessionStartTime)) {
      return 'pending'; // Session hasn't started yet
    } else if (currentTime.isBefore(graceEndTime)) {
      return 'grace'; // Within grace period (on time)
    } else if (currentTime.isBefore(autoCloseTime)) {
      return 'late'; // Late but still accepting check-ins
    } else {
      return 'closed'; // Session closed, no more check-ins
    }
  }

  /// Calculates attendance statistics with time-based insights
  Map<String, dynamic> calculateTimingStatistics({
    required List<AttendanceRecord> records,
    required AttendanceSessionModel session,
  }) {
    if (records.isEmpty) {
      return {
        'total': 0,
        'present': 0,
        'late': 0,
        'absent': 0,
        'avgCheckInTime': null,
        'earliestCheckIn': null,
        'latestCheckIn': null,
        'punctualityRate': 0.0,
      };
    }

    final presentRecords = records.where((r) => r.status == AttendanceStatus.present).toList();
    final lateRecords = records.where((r) => r.status == AttendanceStatus.late).toList();
    final absentRecords = records.where((r) => r.status == AttendanceStatus.absent).toList();
    
    final checkedInRecords = [...presentRecords, ...lateRecords]
        .where((r) => r.checkInTime != null)
        .toList();

    DateTime? earliestCheckIn;
    DateTime? latestCheckIn;
    Duration? totalCheckInDelay = Duration.zero;

    for (final record in checkedInRecords) {
      final checkInTime = record.checkInTime!;
      
      if (earliestCheckIn == null || checkInTime.isBefore(earliestCheckIn)) {
        earliestCheckIn = checkInTime;
      }
      
      if (latestCheckIn == null || checkInTime.isAfter(latestCheckIn)) {
        latestCheckIn = checkInTime;
      }
      
      final delay = checkInTime.difference(session.startTime);
      if (delay.isNegative) {
        // Early arrival, treat as 0 delay
        totalCheckInDelay = totalCheckInDelay! + Duration.zero;
      } else {
        totalCheckInDelay = totalCheckInDelay! + delay;
      }
    }

    final avgCheckInDelayMinutes = checkedInRecords.isNotEmpty
        ? totalCheckInDelay!.inMinutes / checkedInRecords.length
        : 0.0;

    final punctualityRate = records.isNotEmpty
        ? presentRecords.length / records.length
        : 0.0;

    return {
      'total': records.length,
      'present': presentRecords.length,
      'late': lateRecords.length,
      'absent': absentRecords.length,
      'avgCheckInDelayMinutes': avgCheckInDelayMinutes,
      'earliestCheckIn': earliestCheckIn,
      'latestCheckIn': latestCheckIn,
      'punctualityRate': punctualityRate,
      'onTimeCount': presentRecords.length,
      'lateCount': lateRecords.length,
    };
  }

  /// Gets recommended grace period based on choir history
  int getRecommendedGracePeriod({
    required List<AttendanceRecord> historicalRecords,
    required List<AttendanceSessionModel> pastSessions,
  }) {
    if (historicalRecords.isEmpty || pastSessions.isEmpty) {
      return defaultGraceMinutes;
    }

    // Calculate average late arrival time
    final lateRecords = historicalRecords
        .where((r) => r.status == AttendanceStatus.late && r.checkInTime != null)
        .toList();

    if (lateRecords.isEmpty) {
      return defaultGraceMinutes;
    }

    double totalLateMinutes = 0;
    int validRecords = 0;

    for (final record in lateRecords) {
      // Find corresponding session
      final session = pastSessions.firstWhere(
        (s) => s.id == record.sessionId,
        orElse: () => pastSessions.first,
      );

      final lateMinutes = record.checkInTime!.difference(session.startTime).inMinutes;
      if (lateMinutes > 0) {
        totalLateMinutes += lateMinutes;
        validRecords++;
      }
    }

    if (validRecords == 0) {
      return defaultGraceMinutes;
    }

    final avgLateMinutes = totalLateMinutes / validRecords;
    
    // Recommend grace period that would accommodate 80% of late arrivals
    final recommendedGrace = (avgLateMinutes * 0.8).round();
    
    // Keep within reasonable bounds
    return recommendedGrace.clamp(5, 30);
  }
}

class AttendanceRecord {

  AttendanceRecord({
    required this.id,
    required this.sessionId,
    required this.memberId,
    required this.userId,
    required this.choirId,
    required this.eventDate,
    required this.status,
    required this.recordedBy,
    required this.recordedAt,
    this.checkInTime,
    this.notes,
  });
  final String id;
  final String sessionId;
  final String memberId;
  final String userId;
  final String choirId;
  final DateTime eventDate;
  final AttendanceStatus status;
  final String recordedBy;
  final DateTime recordedAt;
  final DateTime? checkInTime;
  final String? notes;
}