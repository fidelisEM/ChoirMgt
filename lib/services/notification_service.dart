import 'package:supabase_flutter/supabase_flutter.dart';
import '../models/models.dart';

class NotificationService {
  factory NotificationService() => _instance;
  NotificationService._internal();
  static final NotificationService _instance = NotificationService._internal();

  final SupabaseClient _supabase = Supabase.instance.client;

  // Create notification
  Future<NotificationModel?> createNotification({
    required String title,
    required String body,
    required NotificationType type,
    required String recipientId,
    String? choirId,
    NotificationPriority priority = NotificationPriority.medium,
    Map<String, dynamic>? data,
  }) async {
    try {
      final notification = NotificationModel(
        id: '', // Will be generated by database
        title: title,
        body: body,
        type: type,
        priority: priority,
        recipientId: recipientId,
        choirId: choirId,
        data: data ?? {},
        createdAt: DateTime.now(),
      );

      final response = await _supabase
          .from('notifications')
          .insert({
            'title': notification.title,
            'body': notification.body,
            'type': notification.type.toString().split('.').last,
            'priority': notification.priority.toString().split('.').last,
            'recipientId': notification.recipientId,
            'choirId': notification.choirId,
            'data': notification.data,
            'isRead': notification.isRead,
            'created_at': notification.createdAt.toIso8601String(),
          })
          .select()
          .single();

      return NotificationModel.fromJson(response);
    } catch (e) {
      return null;
    }
  }

  // Create bulk notifications
  Future<List<NotificationModel>> createBulkNotifications({
    required String title,
    required String body,
    required NotificationType type,
    required List<String> recipientIds,
    String? choirId,
    NotificationPriority priority = NotificationPriority.medium,
    Map<String, dynamic>? data,
  }) async {
    try {
      final notifications = recipientIds
          .map(
            (userId) => {
              'title': title,
              'body': body,
              'type': type.toString().split('.').last,
              'priority': priority.toString().split('.').last,
              'recipientId': userId,
              'choirId': choirId,
              'data': data ?? {},
              'isRead': false,
              'created_at': DateTime.now().toIso8601String(),
            },
          )
          .toList();

      final response = await _supabase
          .from('notifications')
          .insert(notifications)
          .select();

      return response
          .map<NotificationModel>((json) => NotificationModel.fromJson(json))
          .toList();
    } catch (e) {
      return [];
    }
  }

  // Get user notifications
  Future<List<NotificationModel>> getUserNotifications({
    required String userId,
    bool unreadOnly = false,
    int limit = 50,
    int offset = 0,
  }) async {
    try {
      var query = _supabase
          .from('notifications')
          .select()
          .eq('target_user_id', userId);

      if (unreadOnly) {
        query = query.eq('is_read', false);
      }

      final response = await query
          .order('created_at', ascending: false)
          .limit(limit)
          .range(offset, offset + limit - 1);

      return response
          .map<NotificationModel>((json) => NotificationModel.fromJson(json))
          .toList();
    } catch (e) {
      return [];
    }
  }

  // Mark notification as read
  Future<bool> markAsRead(String notificationId) async {
    try {
      await _supabase
          .from('notifications')
          .update({
            'is_read': true,
            'read_at': DateTime.now().toIso8601String(),
          })
          .eq('id', notificationId);

      return true;
    } catch (e) {
      return false;
    }
  }

  // Mark multiple notifications as read
  Future<bool> markMultipleAsRead(List<String> notificationIds) async {
    try {
      await _supabase
          .from('notifications')
          .update({
            'is_read': true,
            'read_at': DateTime.now().toIso8601String(),
          })
          .inFilter('id', notificationIds);

      return true;
    } catch (e) {
      return false;
    }
  }

  // Mark all notifications as read for a user
  Future<bool> markAllAsRead(String userId) async {
    try {
      await _supabase
          .from('notifications')
          .update({
            'is_read': true,
            'read_at': DateTime.now().toIso8601String(),
          })
          .eq('target_user_id', userId)
          .eq('is_read', false);

      return true;
    } catch (e) {
      return false;
    }
  }

  // Delete notification
  Future<bool> deleteNotification(String notificationId) async {
    try {
      await _supabase.from('notifications').delete().eq('id', notificationId);

      return true;
    } catch (e) {
      return false;
    }
  }

  // Get unread count
  Future<int> getUnreadCount(String userId) async {
    try {
      final response = await _supabase
          .from('notifications')
          .select('id')
          .eq('target_user_id', userId)
          .eq('is_read', false)
          .count();

      return response.count;
    } catch (e) {
      return 0;
    }
  }

  // Send attendance reminder
  Future<bool> sendAttendanceReminder({
    required String sessionId,
    required List<String> memberIds,
    required String createdBy,
  }) async {
    try {
      // Get session details
      final session = await _supabase
          .from('attendance_sessions')
          .select('title, date, start_time')
          .eq('id', sessionId)
          .single();

      final sessionDate = DateTime.parse(session['date']);
      final startTime = DateTime.parse(session['start_time']);

      const title = 'Attendance Reminder';
      final message =
          'Don\'t forget about ${session['title']} on ${sessionDate.day}/${sessionDate.month} at ${startTime.hour}:${startTime.minute.toString().padLeft(2, '0')}';

      await createBulkNotifications(
        title: title,
        body: message,
        type: NotificationType.attendanceReminder,
        recipientIds: memberIds,
      );

      return true;
    } catch (e) {
      return false;
    }
  }

  // Send payment reminder
  Future<bool> sendPaymentReminder({
    required String choirId,
    required List<String> memberIds,
    required double amount,
    required String createdBy,
  }) async {
    try {
      const title = 'Payment Reminder';
      final message =
          'You have an outstanding payment of KSH ${amount.toStringAsFixed(2)}. Please make your payment as soon as possible.';

      await createBulkNotifications(
        title: title,
        body: message,
        type: NotificationType.paymentReminder,
        recipientIds: memberIds,
        choirId: choirId,
      );

      return true;
    } catch (e) {
      return false;
    }
  }

  // Send general announcement
  Future<bool> sendAnnouncement({
    required String title,
    required String message,
    required String choirId,
    required List<String> memberIds,
    required String createdBy,
  }) async {
    try {
      await createBulkNotifications(
        title: title,
        body: message,
        type: NotificationType.announcement,
        recipientIds: memberIds,
        choirId: choirId,
      );

      return true;
    } catch (e) {
      return false;
    }
  }

  // Send welcome notification to new member
  Future<bool> sendWelcomeNotification({
    required String userId,
    required String choirId,
    required String choirName,
    required String createdBy,
  }) async {
    try {
      final title = 'Welcome to $choirName!';
      const message =
          'Welcome to our choir! We\'re excited to have you as a member. Please check the app regularly for updates and announcements.';

      await createNotification(
        title: title,
        body: message,
        type: NotificationType.welcome,
        recipientId: userId,
        choirId: choirId,
      );

      return true;
    } catch (e) {
      return false;
    }
  }

  // Send payment confirmation
  Future<bool> sendPaymentConfirmation({
    required String userId,
    required String choirId,
    required double amount,
    required String paymentMethod,
    required String createdBy,
  }) async {
    try {
      const title = 'Payment Confirmed';
      final message =
          'Your payment of KSH ${amount.toStringAsFixed(2)} via $paymentMethod has been confirmed. Thank you!';

      await createNotification(
        title: title,
        body: message,
        type: NotificationType.paymentConfirmation,
        recipientId: userId,
        choirId: choirId,
      );

      return true;
    } catch (e) {
      return false;
    }
  }

  // Clean up old notifications (older than 90 days)
  Future<void> cleanupOldNotifications() async {
    try {
      final ninetyDaysAgo = DateTime.now().subtract(const Duration(days: 90));

      await _supabase
          .from('notifications')
          .delete()
          .lt('created_at', ninetyDaysAgo.toIso8601String());
    } catch (e) {
      // Handle error silently
    }
  }

  // Get notification statistics
  Future<Map<String, dynamic>> getNotificationStats(String userId) async {
    try {
      final notifications = await _supabase
          .from('notifications')
          .select('type, is_read, created_at')
          .eq('target_user_id', userId);

      final total = notifications.length;
      final unread = notifications.where((n) => n['is_read'] == false).length;
      final read = total - unread;

      // Count by type
      final typeBreakdown = <String, int>{};
      for (final notification in notifications) {
        final type = notification['type'] as String;
        typeBreakdown[type] = (typeBreakdown[type] ?? 0) + 1;
      }

      // Recent activity (last 7 days)
      final sevenDaysAgo = DateTime.now().subtract(const Duration(days: 7));
      final recent = notifications.where((n) {
        final createdAt = DateTime.parse(n['created_at']);
        return createdAt.isAfter(sevenDaysAgo);
      }).length;

      return {
        'total': total,
        'unread': unread,
        'read': read,
        'recent': recent,
        'type_breakdown': typeBreakdown,
      };
    } catch (e) {
      return {
        'total': 0,
        'unread': 0,
        'read': 0,
        'recent': 0,
        'type_breakdown': {},
      };
    }
  }
}
